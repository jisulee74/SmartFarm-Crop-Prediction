"""Read-only audit of the published screening campaign; never trains models."""
from pathlib import Path
import hashlib,json
import pandas as pd
import numpy as np
BASE=Path(__file__).resolve().parent
ROOT=BASE.parent/'ax_catalog_experiments/outputs/exhaustive_e6_semantic_screening_v1'
def build():
    selected=pd.read_csv(BASE/'ax_direction/screening_analysis/selected_models.csv')
    pred_path=ROOT/'final_test_predictions.parquet'
    pred=pd.read_parquet(pred_path)
    out={'campaign':'exhaustive_e6_semantic_screening_v1','prediction_sha256':hashlib.sha256(pred_path.read_bytes()).hexdigest(),'targets':{}}
    for row in selected.itertuples():
        target=row.target; manifest=json.loads((ROOT/'prepared'/target/'manifest.json').read_text()); splits={}; sets={}
        for split in ['train','validation','test']:
            path=ROOT/'prepared'/target/(split+'.parquet');sha=hashlib.sha256(path.read_bytes()).hexdigest()
            assert sha==manifest['dataset_hashes'][split]
            d=pd.read_parquet(path); y=d.target.to_numpy(float);sets[split]=set(d.facility_id.astype(str))
            dates={}
            for col in ['feature_date','target_date']:
                dt=pd.to_datetime(d[col]);dates[col+'_start']=str(dt.min().date());dates[col+'_end']=str(dt.max().date())
            splits[split]={'n':len(d),'facilities':len(sets[split]),'zero_rate':float(np.mean(y==0)),'positive_n':int(sum(y>0)),'mean':float(y.mean()),'std':float(y.std()),'max':float(y.max()),'sha256':sha,**dates}
        overlap=any(sets[a]&sets[b] for a,b in [('train','validation'),('train','test'),('validation','test')]);assert not overlap
        d=pred[(pred.Target_ID==target)&(pred.Model_Type==row.model)&(pred.Combination_ID==row.group_id)]
        assert set(d.Seed)=={42,52,62}
        seed_stats=[]
        for seed,g in d.groupby('Seed'):
            assert len(g)==splits['test']['n'] and g.row_id.is_unique
            y=g.target.to_numpy(float);h=g.prediction_bounded.to_numpy(float);e=(y-h)**2
            seed_stats.append({'seed':int(seed),'sse':float(e.sum()),'zero_sse':float(e[y==0].sum()),'prediction_mean':float(h.mean()),'prediction_max':float(h.max())})
        sse=sum(x['sse'] for x in seed_stats)
        out['targets'][target]={'model':row.model,'group_id':row.group_id,'splits':splits,'facility_overlap':overlap,'test':{'zero_error_share':sum(x['zero_sse'] for x in seed_stats)/sse if sse else None,'prediction_mean':float(np.mean([x['prediction_mean'] for x in seed_stats])),'prediction_max':max(x['prediction_max'] for x in seed_stats),'seeds':seed_stats}}
    (BASE/'src/dataset_audit.js').write_text('// Generated by build_dataset_audit.py from frozen prepared data and saved predictions.\nexport const DATASET_AUDIT = '+json.dumps(out,ensure_ascii=False,allow_nan=False)+';\n')
    return out
if __name__=='__main__':
    d=build();print('Audited',len(d['targets']),'targets, 24 splits; facility overlap: none')
